/**
 * Exports ABIs (+ deployed addresses when available) for the web app and the server.
 *
 * Usage (after `npx hardhat build` and optionally an Ignition deploy):
 *   npm run export-abi                                  # → ../web/src/contracts/generated/
 *   npm run export-abi -- --out ../server/src/generated # any other directory
 *   EXPORT_ABI_OUT=/tmp/abi npm run export-abi
 *
 * Output:
 *   <out>/LevelNFT.abi.ts, ForgeCoin.abi.ts   `export const levelNFTAbi = [...] as const` (viem/wagmi typed)
 *   <out>/LevelNFT.json, ForgeCoin.json       { contractName, abi }
 *   <out>/addresses.json                      { "<chainId>": { "LevelNFT": "0x..", "ForgeCoin": "0x.." } }
 *
 * The web/ and server/ directories belong to other owners: this script is only run on purpose by them
 * (or the coordinator); contracts/ never writes there automatically.
 */
import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");

/** Configuration: contracts to export and default output directory. */
export const EXPORT_CONFIG = {
  defaultOutDir: "../web/src/contracts/generated",
  contracts: [
    { name: "LevelNFT", source: "src/LevelNFT.sol", constName: "levelNFTAbi" },
    { name: "ForgeCoin", source: "src/ForgeCoin.sol", constName: "forgeCoinAbi" },
  ],
  ignitionModuleId: "RealmForgeModule",
} as const;

function parseOutDir(): string {
  const i = process.argv.indexOf("--out");
  const fromArg = i !== -1 ? process.argv[i + 1] : undefined;
  return resolve(ROOT, fromArg ?? process.env.EXPORT_ABI_OUT ?? EXPORT_CONFIG.defaultOutDir);
}

function readAddresses(): Record<string, Record<string, string>> {
  const deployments = join(ROOT, "ignition", "deployments");
  const out: Record<string, Record<string, string>> = {};
  if (!existsSync(deployments)) return out;
  for (const dir of readdirSync(deployments)) {
    const m = /^chain-(\d+)$/.exec(dir);
    const file = join(deployments, dir, "deployed_addresses.json");
    if (!m || !existsSync(file)) continue;
    const raw = JSON.parse(readFileSync(file, "utf8")) as Record<string, string>;
    const chain: Record<string, string> = {};
    for (const c of EXPORT_CONFIG.contracts) {
      const addr = raw[`${EXPORT_CONFIG.ignitionModuleId}#${c.name}`];
      if (addr) chain[c.name] = addr;
    }
    out[m[1]] = chain;
  }
  return out;
}

function main() {
  const outDir = parseOutDir();
  mkdirSync(outDir, { recursive: true });

  for (const c of EXPORT_CONFIG.contracts) {
    const artifactPath = join(ROOT, "artifacts", c.source, `${c.name}.json`);
    if (!existsSync(artifactPath)) throw new Error(`Missing ${artifactPath} — run \`npx hardhat build\` first`);
    const { abi } = JSON.parse(readFileSync(artifactPath, "utf8")) as { abi: unknown[] };
    writeFileSync(join(outDir, `${c.name}.json`), JSON.stringify({ contractName: c.name, abi }, null, 2) + "\n");
    writeFileSync(
      join(outDir, `${c.name}.abi.ts`),
      `// Generated by contracts/scripts/export-abi.ts — do not edit.\nexport const ${c.constName} = ${JSON.stringify(abi, null, 2)} as const;\n`,
    );
  }

  const addresses = readAddresses();
  writeFileSync(join(outDir, "addresses.json"), JSON.stringify(addresses, null, 2) + "\n");
  console.log(`Exported ${EXPORT_CONFIG.contracts.length} ABIs + addresses for chains [${Object.keys(addresses).join(", ")}] → ${outDir}`);
}

main();
